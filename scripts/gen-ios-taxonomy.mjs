// Generates the Swift taxonomy for the Hygie Sync iOS app (repo hygie-ios)
// from db/taxonomy.json, so the app and the server cannot drift on which
// types exist, which regime they follow, and which canonical unit each one
// uses. The canonical_unit strings of the taxonomy are HKUnit(from:) strings
// by construction (verified for all 24 distinct units, 2026-08-12).
//
//   node scripts/gen-ios-taxonomy.mjs > ../hygie-ios/HygieSync/Models/Taxonomy.swift
//
// Regenerate and commit on every taxonomy change.
import { readFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const taxonomy = JSON.parse(
  await readFile(join(here, '..', 'db', 'taxonomy.json'), 'utf8')
);

const supported = taxonomy.metric_types.filter((t) => t.supported);
const minute = supported.filter(
  (t) => t.kind === 'quantity' && t.hae_regime === 'minute_cumulative'
);
const quantity = supported.filter(
  (t) => t.kind === 'quantity' && t.hae_regime !== 'minute_cumulative'
);
const category = supported.filter((t) => t.kind === 'category');

const line = (t) =>
  `        .init(identifier: "${t.hk_identifier}", unit: "${t.canonical_unit}"),`;

console.log(`// GENERATED by hygie/scripts/gen-ios-taxonomy.mjs — do not edit by hand.
// Source of truth: hygie/db/taxonomy.json. Regenerate on every taxonomy change.
import Foundation

struct QuantityTypeSpec: Hashable {
    let identifier: String
    /// HKUnit(from:) string, canonical on the server side (native-format.md).
    let unit: String
}

enum Taxonomy {
    /// Discrete quantities: pushed as raw samples with their HealthKit UUID.
    static let quantitySamples: [QuantityTypeSpec] = [
${quantity.map(line).join('\n')}
    ]

    /// Cumulative types: pushed as HealthKit's own per-minute statistics
    /// (two-regime rule, architecture §2). Never pushed as raw samples.
    static let minuteCumulative: [QuantityTypeSpec] = [
${minute.map(line).join('\n')}
    ]

    /// Category types: pushed as raw samples with their HealthKit enum value.
    static let categorySamples: [String] = [
${category.map((t) => `        "${t.hk_identifier}",`).join('\n')}
    ]
}
`);
